    # La transacción ajena terminó y PostgreSQL soltó el candado por sí solo.
    assert candados_del_etl(clon) == 0
    assert el_candado_esta_libre(clon)
    assert ejecutar_etl(clon.engine).hechos_nuevos == 0
    assert huella(clon) == antes


