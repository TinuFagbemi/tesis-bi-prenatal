def candados_del_etl(base: BaseTemporal) -> int:
    return base.escalar(
        "SELECT count(*) FROM pg_locks WHERE locktype = 'advisory' "
        "AND classid = 0 AND objid = :clave AND objsubid = 1",
        clave=CLAVE_DEL_CANDADO,
    )


def el_candado_esta_libre(base: BaseTemporal) -> bool:
    """Otra transacción puede tomarlo ahora mismo (y lo suelta al terminar)."""
    with base.engine.connect() as conexion:
        with conexion.begin():
            return bool(
                conexion.execute(
                    select(func.pg_try_advisory_xact_lock(CLAVE_DEL_CANDADO))
                ).scalar_one()
            )


@contextmanager
def otra_ejecucion_con_el_candado(base: BaseTemporal, *, confirmar: bool):
    """Una transacción ajena que toma el candado igual que el ETL y lo retiene."""
    conexion = base.engine.connect()
    transaccion = conexion.begin()
    try:
        assert conexion.execute(
            select(func.pg_try_advisory_xact_lock(CLAVE_DEL_CANDADO))
        ).scalar_one()
        yield
    finally:
        (transaccion.commit if confirmar else transaccion.rollback)()
        conexion.close()


