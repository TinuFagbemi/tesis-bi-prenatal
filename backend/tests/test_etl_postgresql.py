def _datos_personales(base: BaseTemporal) -> list[str]:
    valores = []
    for sql in (
        f"SELECT cedula, nombre_completo, telefono_pac FROM {A}.dim_paciente",
        f"SELECT nombre_completo, email_med, telefono_med FROM {A}.dim_medico",
    ):
        for fila in base.filas(sql):
            valores += [str(valor) for valor in fila if valor]
    return valores


