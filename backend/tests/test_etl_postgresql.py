def test_el_esquema_operacional_se_despliega_con_los_nombres_de_siempre(base_vacia):
    """The analytic registry must not change how the operational schema is built.

    Alembic names the CHECK constraints that back the enums of the first
    revision through the naming convention of ``target_metadata``. A regression
    in ``env.py`` would create them under their bare names on a fresh database,
    and only a deployment from scratch shows it.
    """
    migrar(base_vacia.url, "head")
    inspector = inspect(base_vacia.engine)

    desplegados = {
        (tabla, check["name"])
        for tabla in TABLAS_ESPERADAS
        for check in inspector.get_check_constraints(tabla, schema=O)
    }
    declarados = {
        (tabla.name, restriccion.name)
        for tabla in Base.metadata.tables.values()
        for restriccion in tabla.constraints
        if isinstance(restriccion, CheckConstraint)
    }

    assert desplegados == declarados


def test_la_estructura_desplegada_es_la_de_la_metadata(base_vacia):
    migrar(base_vacia.url, "head")
    inspector = inspect(base_vacia.engine)

    for tabla in TABLAS_ANALITICAS:
        nombre = tabla.name
        pk = inspector.get_pk_constraint(nombre, schema=A)
        assert tuple(pk["constrained_columns"]) == tuple(c.name for c in tabla.primary_key)
        assert pk["name"] == tabla.primary_key.name

        reflejadas = {
            (fk["name"], tuple(fk["constrained_columns"]), fk["referred_schema"],
             fk["referred_table"], tuple(fk["referred_columns"]),
             fk["options"].get("ondelete"))
            for fk in inspector.get_foreign_keys(nombre, schema=A)
        }
        declaradas = {
            (fk.name, tuple(fk.column_keys), A, fk.referred_table.name,
             tuple(e.column.name for e in fk.elements), fk.ondelete)
            for fk in tabla.foreign_key_constraints
        }
        assert reflejadas == declaradas

        assert {u["name"] for u in inspector.get_unique_constraints(nombre, schema=A)} == {
            c.name for c in tabla.constraints if c.__class__.__name__ == "UniqueConstraint"
        }
        assert {c["name"] for c in inspector.get_check_constraints(nombre, schema=A)} == {
            c.name for c in tabla.constraints if c.__class__.__name__ == "CheckConstraint"
        }
        assert {
            i["name"] for i in inspector.get_indexes(nombre, schema=A)
            if not i.get("duplicates_constraint")
        } == {i.name for i in tabla.indexes}

        columnas = {c["name"]: c for c in inspector.get_columns(nombre, schema=A)}
        for columna in tabla.columns:
            assert columnas[columna.name]["nullable"] == columna.nullable


