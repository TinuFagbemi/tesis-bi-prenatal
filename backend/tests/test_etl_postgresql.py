def test_una_colision_en_el_hecho_revierte_en_lugar_de_saltarse_la_fila(clon, monkeypatch):
    """A plain INSERT: a candidate whose key already exists is an anomaly.

    The race is simulated: between the anti-join and the INSERT, a row with the
    candidate's key appears in the fact. ``ON CONFLICT DO NOTHING`` would skip
    it and report success; the plain INSERT fails and the whole run -- the
    intruding row included -- is rolled back.
    """
    ejecutar_etl(clon.engine)
    antes = huella(clon)
    sesion = nueva_sesion(clon, "2025-02-27T15:00:00+00:00", "2025-02-27T15:05:00+00:00")
    candidata = nueva_lectura(clon, sesion, "2025-02-27T15:01:00+00:00", semana=SEMANA_8)

    original = extraccion.extraer_lecturas_nuevas

    def carrera(conexion):
        filas = original(conexion)
        conexion.execute(
            text(
                f"INSERT INTO {A}.fact_lectura_biometrica SELECT :id, id_sesion, "
                "id_paciente, id_medico, id_clinica, id_tiempo_gestacional, id_embarazo, "
                "id_semaforo, hr_valor, spo2_valor, mov_valor, estado_hr, estado_spo2, "
                f"estado_mov, fecha_hora FROM {A}.fact_lectura_biometrica "
                "WHERE hr_valor IS NOT NULL ORDER BY id_lectura LIMIT 1"
            ),
            {"id": candidata},
        )
        return filas

    monkeypatch.setattr(extraccion, "extraer_lecturas_nuevas", carrera)

    with pytest.raises(CargaInconsistente, match="SQLSTATE 23505"):
        ejecutar_etl(clon.engine)

