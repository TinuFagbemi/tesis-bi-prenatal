# ---------------------------------------------------------------------------
# 10. Concurrencia real: dos solicitudes, dos conexiones, un solo ganador
# ---------------------------------------------------------------------------
#
# Lo que estas pruebas tienen que demostrar no es que dos peticiones «salgan a la
# vez» -- eso no prueba nada, porque nada garantiza que se encuentren en el punto
# que importa. Lo que hay que demostrar es que **la perdedora llegó a PostgreSQL
# y se quedó esperando a la transacción de la ganadora**, y para eso hace falta
# detener a la ganadora en un punto conocido, posterior a su reclamación.
#
# La coreografía usa un candado que el propio endpoint toma sin saberlo, así que
# no hay ni un hook de prueba en el código productivo:
#
#   1. Una conexión de control toma ``LOCK TABLE operacional.embarazo IN ACCESS
#      EXCLUSIVE MODE``. Ese modo entra en conflicto con el ACCESS SHARE que toma
#      cualquier ``SELECT``.
#   2. La solicitud A entra: consulta la vía rápida y **reclama la clave** -- la
#      tabla de idempotencia no está bloqueada --, y queda detenida en el primer
#      ``SELECT`` de ``verificar_referencias``, que lee ``embarazo``. Su
#      transacción sigue abierta, con la reclamación tomada y sin confirmar.
#   3. La solicitud B entra con la misma clave y queda detenida en su
#      ``INSERT ... ON CONFLICT``, bloqueada por la entrada no confirmada de A en
#      el índice único.
#   4. Se comprueba con ``pg_blocking_pids`` que **B está bloqueada por A**. Ésa
#      es la evidencia, y no la simultaneidad del arranque.
#   5. El control libera. A continúa y decide el desenlace.
#
# Sobre las esperas: no se usan sleeps fijos para asumir simultaneidad; se
# sondean condiciones observables con intervalos breves y un deadline. Si la
# condición no se cumple, la prueba falla por tiempo agotado en vez de continuar
# a ciegas.

TIEMPO_MAXIMO_DE_ESPERA = 20.0
INTERVALO_DE_SONDEO = 0.02
TIEMPO_MAXIMO_DE_RESPUESTA = 30.0

# Último recurso, del lado del servidor. La coordinación de Python ya libera el
# candado en un ``finally``, pero si *esa* liberación fallara, un worker seguiría
# esperando dentro de PostgreSQL y ninguna cantidad de deadlines en Python lo
# desbloquearía: el hilo no se puede interrumpir desde fuera. Con estos límites
# el servidor aborta la sentencia por su cuenta, el worker termina y el proceso
# no puede quedarse colgado -- ni siquiera en el ``atexit`` de
# ``concurrent.futures``, que sí hace join de los hilos vivos.
#
# Se aplican **solo a las conexiones de este arnés**: no tocan la configuración
# del servidor ni la del engine de la aplicación.
#
# Son mayores que ``TIEMPO_MAXIMO_DE_ESPERA`` a propósito, para que en el camino
# normal nunca se disparen antes que la coordinación.
ESPERA_MAXIMA_DE_CANDADO = "25s"
ESPERA_MAXIMA_DE_SENTENCIA = "30s"
OPCIONES_DE_LIMITE = (
    f"-c lock_timeout={ESPERA_MAXIMA_DE_CANDADO} "
    f"-c statement_timeout={ESPERA_MAXIMA_DE_SENTENCIA}"
)

# Prefijo de todo lo que crean los escenarios concurrentes. Es lo que permite
# limpiar exactamente lo que se creó, sin TRUNCATE y sin borrados generales.
MARCA = "SCRUM63C"

# Cabecera exclusiva de las pruebas: dice a qué participante pertenece la
# solicitud. No la lee ni la conoce el código productivo -- solo la sustitución
# de ``get_db`` que instalan estas pruebas.
#
# Hizo falta porque un ``threading.local`` no sirve aquí: FastAPI ejecuta un
# endpoint síncrono, y sus dependencias, en un hilo del threadpool, no en el que
# envía la petición. El engine tiene que viajar con la solicitud, y la cabecera
# es la forma más simple de que lo haga.
CABECERA_PARTICIPANTE = "X-Participante-De-Prueba"

_ENGINES_POR_PARTICIPANTE: dict[str, Any] = {}


def _sesion_del_participante(peticion: Request):
    """Dependencia ``get_db`` durante la concurrencia: una Session por petición.

    Cada solicitud abre su propia ``Session`` sobre el engine de su participante,
    y cada engine tiene su propia conexión. No se comparte ninguna, y no se
    reutiliza la ``sesion_de_pruebas`` secuencial.
    """
    engine = _ENGINES_POR_PARTICIPANTE[peticion.headers[CABECERA_PARTICIPANTE]]
    sesion = Session(bind=engine)
    try:
        yield sesion
    finally:
        sesion.close()


@dataclass
class Participante:
    """Una solicitud concurrente con todo lo suyo: engine, conexión y cliente."""

    nombre: str
    engine: Any
    cliente: TestClient


def esperar_a(
    condicion,
    descripcion: str,
    limite: float = TIEMPO_MAXIMO_DE_ESPERA,
    futuros=(),
):
    """Sondea una condición observable hasta que se cumpla, o falla por deadline.

    El ``sleep`` de aquí dentro es el intervalo entre sondeos, nunca el
    mecanismo de sincronización: lo que decide es la condición, y el límite
    existe para que una prueba concurrente no pueda dejar CI colgado.

    ``futuros`` son las solicitudes que deberían seguir en vuelo. Si alguna
    termina antes de que la condición se cumpla, la espera se corta y se reporta
    **su** desenlace: una petición que murió pronto explica el problema, y
    esperar veinte segundos para decir «tiempo agotado» lo esconde.
    """
    fin = time.monotonic() + limite
    while time.monotonic() < fin:
        valor = condicion()
        if valor:
            return valor
        for futuro in futuros:
            if futuro.done():
                try:
                    respuesta = futuro.result(timeout=1)
                except Exception as error:  # noqa: BLE001 -- se reporta tal cual
                    pytest.fail(
                        f"Una solicitud terminó con una excepción mientras se "
                        f"esperaba «{descripcion}»: "
                        f"{type(error).__name__}: {error}"
                    )
                pytest.fail(
                    f"Una solicitud terminó antes de tiempo mientras se esperaba "
                    f"«{descripcion}»: http={respuesta.status_code} "
                    f"cuerpo={respuesta.text[:300]}"
                )
        time.sleep(INTERVALO_DE_SONDEO)
    pytest.fail(f"Tiempo agotado ({limite}s) esperando: {descripcion}")


def pid_de(observador, nombre_app: str):
    return observador.execute(
        text("select pid from pg_stat_activity where application_name = :n"),
        {"n": nombre_app},
    ).scalar()


def bloqueado_por(observador, pid: int) -> list[int]:
    return list(
        observador.execute(text("select pg_blocking_pids(:p)"), {"p": pid}).scalar() or []
    )


def esta_esperando_un_candado(observador, pid: int) -> bool:
    fila = observador.execute(
        text("select wait_event_type from pg_stat_activity where pid = :p"), {"p": pid}
    ).scalar()
    return fila == "Lock"


