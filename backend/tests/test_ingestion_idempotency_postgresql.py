def _variables_de_entorno_leidas() -> set[str]:
    """Literales que este módulo usa para leer ``os.environ``, según su AST.

    Se mira el árbol sintáctico y no el texto del archivo: buscar cadenas
    prohibidas en la propia fuente es una comprobación que se derrota a sí misma,
    porque el nombre aparecería justamente en la línea que lo prohíbe.
    """
    import ast
    from pathlib import Path

    arbol = ast.parse(Path(__file__).read_text(encoding="utf-8"))
    nombres: set[str] = set()

    def _es_environ(nodo) -> bool:
        return isinstance(nodo, ast.Attribute) and nodo.attr == "environ"

    for nodo in ast.walk(arbol):
        # os.environ["X"]
        if isinstance(nodo, ast.Subscript) and _es_environ(nodo.value):
            if isinstance(nodo.slice, ast.Constant):
                nombres.add(nodo.slice.value)
            elif isinstance(nodo.slice, ast.Name):
                nombres.add(f"<variable {nodo.slice.id}>")
        # os.environ.get("X")
        if (
            isinstance(nodo, ast.Call)
            and isinstance(nodo.func, ast.Attribute)
            and nodo.func.attr == "get"
            and _es_environ(nodo.func.value)
            and nodo.args
        ):
            primero = nodo.args[0]
            if isinstance(primero, ast.Constant):
                nombres.add(primero.value)
            elif isinstance(primero, ast.Name):
                nombres.add(f"<variable {primero.id}>")
    return nombres


