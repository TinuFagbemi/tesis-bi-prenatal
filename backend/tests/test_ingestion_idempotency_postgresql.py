@dataclass
class Carrera:
    """Lo observado durante la carrera, para que las pruebas lo afirmen."""

    respuesta_a: Any
    respuesta_b: Any
    pid_a: int
    pid_b: int
    bloqueadores_de_b: list[int]
    b_esperaba_un_candado: bool


def liberar_el_control(control) -> None:
    """Suelta el candado del control. Idempotente y tolerante a fallos.

    Se llama dos veces a propósito: en el paso 5 del camino normal, que es
    cuando la carrera tiene que resolverse, y otra vez en el ``finally``, que es
    lo que cubre todos los caminos de error. Un segundo ``rollback`` sobre una
    conexión sin transacción abierta no hace nada.

    Si la conexión ya está inservible, el error se descarta: estamos en la
    limpieza, y tapar la excepción que nos trajo hasta aquí sería peor que no
    poder soltar un candado que los límites del servidor van a resolver igual.
    """
    try:
        control.rollback()
    except SQLAlchemyError:
        pass


def correr_carrera(entorno: EntornoConcurrente, cuerpo_a, cuerpo_b) -> Carrera:
    """Ejecuta la coreografía completa y devuelve la evidencia recogida.

    **Por qué el executor se gestiona a mano y no con ``with``.** El
    ``__exit__`` de ``ThreadPoolExecutor`` llama a ``shutdown(wait=True)``, que
    espera a que terminen los workers en vuelo. En el camino normal eso es
    inocuo, pero en cualquier camino de error sería una trampa: las dos
    solicitudes están bloqueadas dentro de PostgreSQL esperando el candado que
    tiene el control, el ``finally`` que lo suelta todavía no ha corrido, y la
    espera no termina nunca. Los deadlines de arriba quedarían anulados
    justamente cuando hacen falta.

    Así que el orden es el inverso: primero se suelta el candado —lo que deja a
    los workers terminar—, y solo después se cierra el executor **sin esperar**.
    """
    a, b = entorno.participantes
    observador = entorno.observador

    # 1. El control detiene cualquier lectura de 'embarazo'.
    entorno.control.execute(
        text(f"LOCK TABLE {SCHEMA_OPERACIONAL}.embarazo IN ACCESS EXCLUSIVE MODE")
    )

    ejecutor = ThreadPoolExecutor(max_workers=2)
    try:
        futuro_a = ejecutor.submit(enviar, a, cuerpo_a, entorno.clave)

        # 2. A reclamó la clave y quedó detenida al leer 'embarazo'.
        pid_a = esperar_a(
            lambda: pid_de(observador, a.nombre),
            "que la solicitud A abra su conexión",
            futuros=(futuro_a,),
        )
        esperar_a(
            lambda: esta_esperando_un_candado(observador, pid_a),
            "que la solicitud A quede esperando el candado de la tabla",
            futuros=(futuro_a,),
        )
        esperar_a(
            lambda: contar_reclamaciones_en(observador, entorno.clave) == 0,
            "que la reclamación de A siga sin confirmar",
            futuros=(futuro_a,),
        )

        futuro_b = ejecutor.submit(enviar, b, cuerpo_b, entorno.clave)

        # 3-4. B llegó a PostgreSQL y espera por la transacción de A.
        pid_b = esperar_a(
            lambda: pid_de(observador, b.nombre),
            "que la solicitud B abra su conexión",
            futuros=(futuro_b,),
        )
        bloqueadores = esperar_a(
            lambda: (
                bloqueado_por(observador, pid_b)
                if pid_a in bloqueado_por(observador, pid_b)
                else None
            ),
            "que la solicitud B quede bloqueada por la transacción de A",
            futuros=(futuro_b,),
        )
        b_esperaba = esta_esperando_un_candado(observador, pid_b)

        # 5. Se libera y cada una decide su desenlace.
        liberar_el_control(entorno.control)

        respuesta_a = futuro_a.result(timeout=TIEMPO_MAXIMO_DE_RESPUESTA)
        respuesta_b = futuro_b.result(timeout=TIEMPO_MAXIMO_DE_RESPUESTA)
    finally:
        # El orden importa: soltar el candado desbloquea a los workers, y solo
        # entonces se cierra el executor. ``wait=False`` es lo que garantiza que
        # ningún camino de error se quede atrapado aquí, y ``cancel_futures``
        # descarta lo que aún no hubiera arrancado.
        liberar_el_control(entorno.control)
        ejecutor.shutdown(wait=False, cancel_futures=True)

    return Carrera(
        respuesta_a=respuesta_a,
        respuesta_b=respuesta_b,
        pid_a=pid_a,
        pid_b=pid_b,
        bloqueadores_de_b=bloqueadores,
        b_esperaba_un_candado=b_esperaba,
    )


def contar_reclamaciones_en(conexion, clave: str) -> int:
    return conexion.execute(
        select(func.count())
        .select_from(IdempotenciaSolicitud)
        .where(IdempotenciaSolicitud.clave == clave)
    ).scalar_one()


