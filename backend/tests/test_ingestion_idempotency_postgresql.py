def _revision_estampada(engine) -> str | None:
    with engine.connect() as conexion:
        existe = conexion.execute(
            text("select to_regclass('public.alembic_version')")
        ).scalar()
        if existe is None:
            return None
        return conexion.execute(text("select version_num from alembic_version")).scalar()


def _tiene_la_tabla(engine) -> bool:
    return inspect(engine).has_table(TABLA_IDEMPOTENCIA, schema=SCHEMA_OPERACIONAL)


@pytest.fixture(scope="module")
def ciclo_de_la_revision(engine_de_pruebas, url_de_pruebas):
    """``head -> 150788f88be7 -> head``, ejecutado una sola vez y fotografiado.

    Es el único punto de esta suite que ejecuta DDL, y por eso comprueba antes
    que la base conectada es la dedicada, **por nombre**. Contra cualquier otra
    aborta sin tocar nada: un downgrade borra la tabla de idempotencia.
    """
    with engine_de_pruebas.connect() as conexion:
        nombre = conexion.execute(text("select current_database()")).scalar()
    if nombre != NOMBRE_DE_BASE_REQUERIDO:
        pytest.fail(
            f"{VARIABLE_DE_ENTORNO} apunta a la base '{nombre}'. Este ciclo "
            f"revierte y reaplica una revisión, así que solo se ejecuta contra "
            f"la base dedicada '{NOMBRE_DE_BASE_REQUERIDO}'."
        )

    config = construir_config_alembic()
    fotografia: dict[str, Any] = {"partida": _revision_estampada(engine_de_pruebas)}

    with pytest.MonkeyPatch.context() as parche:
        # alembic/env.py resuelve la URL desde settings, no desde el Config: esto
        # es lo que de verdad mantiene el ciclo lejos de la base de desarrollo.
        parche.setattr(settings, "database_url", url_de_pruebas)

        # The target is named, not relative: «-1» would now revert the analytic
        # revision that sits on top, and this cycle is about SCRUM-63's. Going
        # down to the initial revision takes every later revision with it.
        command.downgrade(config, REVISION_INICIAL)
        fotografia["tras_downgrade"] = _revision_estampada(engine_de_pruebas)
        fotografia["tabla_tras_downgrade"] = _tiene_la_tabla(engine_de_pruebas)

        command.upgrade(config, "head")
        fotografia["tras_upgrade"] = _revision_estampada(engine_de_pruebas)
        fotografia["tabla_tras_upgrade"] = _tiene_la_tabla(engine_de_pruebas)

        try:
            command.check(config)
            fotografia["diferencias"] = None
        except AutogenerateDiffsDetected as error:
            fotografia["diferencias"] = str(error)

    return fotografia


