def test_base_existente_con_37_cuentas_upgrade_downgrade_upgrade(base_previa):
    assert revision_de(base_previa) == REVISION_ANALITICA
    antes = conteos(base_previa)
    usuarios_antes = huella(base_previa, f"{O}.usuario")
    vinculos_antes = huella(base_previa, f"{O}.usuario_paciente") + huella(base_previa, f"{O}.usuario_medico")
    assert antes == CONTEOS_CANONICOS
    assert not existe_check_email(base_previa) and not existe_funcion(base_previa)

    migrar(base_previa.url, "head")
    assert revision_de(base_previa) == REVISION_SCRUM_97
    assert conteos(base_previa) == antes
    assert huella(base_previa, f"{O}.usuario") == usuarios_antes
    assert set(triggers_de(base_previa)) == set(TRIGGERS)

    revertir(base_previa.url, REVISION_ANALITICA)
    assert revision_de(base_previa) == REVISION_ANALITICA
    assert triggers_de(base_previa) == {}
    assert not existe_check_email(base_previa) and not existe_funcion(base_previa)
    assert conteos(base_previa) == antes
    assert huella(base_previa, f"{O}.usuario") == usuarios_antes

    migrar(base_previa.url, "head")
    assert conteos(base_previa) == antes
    assert (
        huella(base_previa, f"{O}.usuario_paciente") + huella(base_previa, f"{O}.usuario_medico")
        == vinculos_antes
    )
    assert diferencias_de_alembic(base_previa.url) is None


