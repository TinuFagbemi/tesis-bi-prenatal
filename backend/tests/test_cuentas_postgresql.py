@dataclass
class Carrera:
    a: Any
    b: Any


@contextmanager
def participantes(base: BaseTemporal):
    """Dos clientes, cada uno con su engine y su application_name."""
    engines = {
        letra: create_engine(
            base.url,
            poolclass=NullPool,
            connect_args={"application_name": f"scrum97-{letra}", "options": OPCIONES_DE_LIMITE},
        )
        for letra in "AB"
    }

    def _engine(peticion: Request):
        return engines[peticion.headers[CABECERA_PARTICIPANTE]]

    def sesion_negocio(peticion: Request):
        with Session(bind=_engine(peticion), autoflush=False) as sesion_bd:
            yield sesion_bd

    def sesion_auditoria(peticion: Request):
        with Session(bind=_engine(peticion), autoflush=False) as sesion_bd:
            yield sesion_bd

    app.dependency_overrides[get_db] = sesion_negocio
    app.dependency_overrides[get_db_auditoria] = sesion_auditoria
    app.dependency_overrides[obtener_configuracion_jwt] = lambda: CONFIGURACION
    clientes = {
        letra: TestClient(app, raise_server_exceptions=False, headers={CABECERA_PARTICIPANTE: letra})
        for letra in "AB"
    }
    try:
        yield clientes
    finally:
        app.dependency_overrides.clear()
        for letra in "AB":
            clientes[letra].close()
            engines[letra].dispose()


def correr(base: BaseTemporal, bloqueo: list[str], a: Callable, b: Callable) -> Carrera:
    """Un control toma el candado, A y B esperan ambos, el control suelta.

    Lo que sincroniza es PostgreSQL: se sondea ``pg_stat_activity`` hasta que las
    dos conexiones esperan un candado, y solo entonces se libera. El sondeo va por
    un observador en autocommit: dentro de una transaccion PostgreSQL devuelve la
    misma foto de esa vista en cada lectura, y el control nunca veria la espera.
    """
    control = base.engine.connect()
    observador = base.engine.connect().execution_options(isolation_level="AUTOCOMMIT")
    transaccion = control.begin()
    try:
        for sentencia in bloqueo:
            control.execute(text(sentencia))
        with participantes(base) as clientes, ThreadPoolExecutor(max_workers=2) as pool:
            futuro_a = pool.submit(a, clientes["A"])
            futuro_b = pool.submit(b, clientes["B"])
            limite = time.monotonic() + TIEMPO_MAXIMO_DE_ESPERA
            while True:
                esperando = observador.execute(
                    text(
                        "SELECT count(*) FROM pg_stat_activity WHERE application_name"
                        " IN ('scrum97-A', 'scrum97-B') AND wait_event_type = 'Lock'"
                    )
                ).scalar()
                if esperando == 2:
                    break
                for futuro in (futuro_a, futuro_b):
                    if futuro.done():
                        pytest.fail(f"Un participante termino antes de la carrera: {futuro.result()}")
                if time.monotonic() > limite:
                    pytest.fail("Los dos participantes no llegaron a esperar el candado.")
                time.sleep(0.05)
            transaccion.rollback()
            return Carrera(a=futuro_a.result(timeout=90), b=futuro_b.result(timeout=90))
    finally:
        if transaccion.is_active:
            transaccion.rollback()
        control.close()
        observador.close()


def estados(carrera: Carrera) -> list[int]:
    return sorted([carrera.a.status_code, carrera.b.status_code])


