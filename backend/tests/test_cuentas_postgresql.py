def error_de_commit(base: BaseTemporal, *sentencias: str) -> DBAPIError | None:
    """Ejecuta las sentencias en una transaccion y devuelve el error del commit, si hay."""
    try:
        with base.engine.begin() as conexion:
            for sentencia in sentencias:
                conexion.execute(text(sentencia))
    except DBAPIError as error:
        return error
    return None


def restriccion_de(error: DBAPIError) -> tuple[str | None, str | None]:
    original = error.orig
    return getattr(original, "sqlstate", None), getattr(original.diag, "constraint_name", None)


