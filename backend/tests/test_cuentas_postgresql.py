    if ruta == "medicos":
        return cliente.post(RUTA_MEDICO.format(id_objetivo), json=cuerpo, headers=cabeceras)
    return cliente.patch(RUTA_ESTADO.format(id_objetivo), json={"activo": False}, headers=cabeceras)


