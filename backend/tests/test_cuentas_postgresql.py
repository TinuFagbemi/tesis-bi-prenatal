    id_usuario = id_de_cuenta(base, "paciente02@example.com")
    base.escribir(f"UPDATE {O}.usuario SET activo = :a WHERE id_usuario = :id", a=inicial, id=id_usuario)

    carrera = correr(
        base,
        [f"SELECT id_usuario FROM {O}.usuario WHERE id_usuario = {id_usuario} FOR UPDATE"],
        lambda c: cambiar_estado(c, token_admin, id_usuario, pedido_a),
        lambda c: cambiar_estado(c, token_admin, id_usuario, pedido_b),
    )

