def test_no_se_creo_ningun_tipo_enum_nativo(ciclo):
    """A native ENUM would survive downgrade and block a value list change."""
    url = os.environ[VARIABLE_DE_ENTORNO]
    engine = create_engine(url)
    with engine.connect() as conexion:
        nativos = conexion.execute(
            text(
                "select count(*) from pg_type t"
                " join pg_namespace n on n.oid = t.typnamespace"
                " where t.typtype = 'e' and n.nspname = :esquema"
            ),
            {"esquema": SCHEMA_OPERACIONAL},
        ).scalar()
    engine.dispose()

    assert nativos == 0


