"""Optional round trip of the initial revision against a real PostgreSQL server.

Skipped unless ``SCRUM52_TEST_DATABASE_URL`` is set, so the normal suite stays
offline and CI does not need a database. When it is set, the module runs the
full cycle once per session::

    upgrade head -> inspect -> downgrade base -> upgrade head -> alembic check

and leaves the database at ``head`` so the evidence can be captured afterwards
with psql or pgAdmin.

Safety rails, because the cycle drops and recreates the whole ``operacional``
schema:

* the connected database must be named exactly ``scrum52_validacion_tmp``;
  anything else aborts before a single statement runs;
* an ``operacional`` schema that this revision did not stamp aborts as well,
  rather than being taken over;
* the database is never created, never dropped, and its URL is never printed.

Run it from ``backend/`` with::

    $env:SCRUM52_TEST_DATABASE_URL = "postgresql+psycopg://<usuario>:<clave>@127.0.0.1:<puerto>/scrum52_validacion_tmp"
    .\\.venv\\Scripts\\python.exe -m pytest tests/test_migration_postgresql.py -v
"""

