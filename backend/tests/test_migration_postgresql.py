def test_las_llaves_foraneas_desplegadas_apuntan_a_donde_deben(ciclo):
    desplegadas = {
        (tabla, columna): (tabla_ref, columna_ref)
        for tabla, columna, tabla_ref, columna_ref, _ in (
            ciclo.estructura_tras_primer_upgrade.llaves_foraneas
        )
    }

    assert desplegadas == FOREIGN_KEYS_ESPERADAS


def test_las_politicas_on_delete_desplegadas_coinciden(ciclo):
    desplegadas = {
        (tabla, columna): politica
        for tabla, columna, _, _, politica in (
            ciclo.estructura_tras_primer_upgrade.llaves_foraneas
        )
    }

    assert desplegadas == ONDELETE_ESPERADOS


@pytest.mark.parametrize("politica", ["RESTRICT", "CASCADE"])
def test_cantidad_de_politicas_desplegadas(politica, ciclo):
    esperadas = sum(1 for p in ONDELETE_ESPERADOS.values() if p == politica)
    desplegadas = sum(
        1
        for *_, encontrada in ciclo.estructura_tras_primer_upgrade.llaves_foraneas
        if encontrada == politica
    )

    assert desplegadas == esperadas


