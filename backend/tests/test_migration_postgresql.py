def _insertar_lecturas(conexion, id_sesion: int, cantidad: int) -> list[int]:
    """Insert ``cantidad`` distinct maternal-vitals readings on the same session."""
    id_tiempo_gest, id_semaforo = _sembrar_catalogos_de_lectura(conexion)
    captura = datetime(2026, 6, 1, 8, 0, tzinfo=timezone.utc)
    lectura = tabla_operacional("lectura_biometrica")

    return [
        conexion.execute(
            insert(lectura)
            .values(
                id_sesion=id_sesion,
                id_tiempo_gest=id_tiempo_gest,
                id_semaforo=id_semaforo,
                fecha_hora_captura=captura + timedelta(minutes=5 * i),
                hr_valor=Decimal("78.50") + i,
                spo2_valor=Decimal("97.00"),
            )
            .returning(lectura.c.id_lectura)
        ).scalar_one()
        for i in range(cantidad)
    ]


def test_postgresql_acepta_cinco_lecturas_en_la_misma_sesion(conexion_revertible):
    """The 1:N is only real if the server itself accepts the five inserts."""
    id_sesion = _sembrar_sesion(conexion_revertible)

    ids = _insertar_lecturas(conexion_revertible, id_sesion, LECTURAS_POR_SESION)

    assert len(set(ids)) == LECTURAS_POR_SESION

    lectura = tabla_operacional("lectura_biometrica")
    filas = conexion_revertible.execute(
        select(lectura.c.id_lectura, lectura.c.id_sesion).where(
            lectura.c.id_sesion == id_sesion
        )
    ).all()

    assert len(filas) == LECTURAS_POR_SESION
    # Cada lectura sigue perteneciendo a una sola sesión: la misma para las cinco.
    assert {fila.id_sesion for fila in filas} == {id_sesion}
    assert {fila.id_lectura for fila in filas} == set(ids)


def test_borrar_la_sesion_arrastra_sus_lecturas_por_cascade(conexion_revertible):
    """ON DELETE CASCADE must still remove every reading of the session."""
    id_sesion = _sembrar_sesion(conexion_revertible)
    _insertar_lecturas(conexion_revertible, id_sesion, LECTURAS_POR_SESION)
    lectura = tabla_operacional("lectura_biometrica")

    def cuantas() -> int:
        return len(
            conexion_revertible.execute(
                select(lectura.c.id_lectura).where(lectura.c.id_sesion == id_sesion)
            ).all()
        )

    assert cuantas() == LECTURAS_POR_SESION

    sesion = tabla_operacional("sesion_monitoreo")
    conexion_revertible.execute(delete(sesion).where(sesion.c.id_sesion == id_sesion))

    assert cuantas() == 0


