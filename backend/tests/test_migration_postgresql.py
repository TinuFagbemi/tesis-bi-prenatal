@dataclass
class EstructuraDesplegada:
    """Snapshot of what actually exists in the server after an upgrade."""

    tablas: set[str] = field(default_factory=set)
    llaves_primarias: dict[str, tuple[str, ...]] = field(default_factory=dict)
    llaves_foraneas: set[tuple[str, str, str, str, str | None]] = field(
        default_factory=set
    )
    indices_explicitos: set[tuple[str, str, tuple[str, ...]]] = field(
        default_factory=set
    )
    restricciones_unique: set[tuple[str, str, tuple[str, ...]]] = field(
        default_factory=set
    )
    restricciones_check: set[tuple[str, str]] = field(default_factory=set)
    columnas: dict[str, set[str]] = field(default_factory=dict)
    columnas_nullable: dict[str, set[str]] = field(default_factory=dict)
    tipos: dict[tuple[str, str], str] = field(default_factory=dict)


def _describir_tipo(tipo) -> str:
    """``str(tipo)`` alone hides the time zone flag of TIMESTAMP columns."""
    if getattr(tipo, "timezone", False):
        return f"{tipo} WITH TIME ZONE"
    return str(tipo)


def _tomar_estructura(engine) -> EstructuraDesplegada:
    inspector = inspect(engine)
    estructura = EstructuraDesplegada()
    estructura.tablas = set(inspector.get_table_names(schema=SCHEMA_OPERACIONAL))

    for tabla in sorted(estructura.tablas):
        pk = inspector.get_pk_constraint(tabla, schema=SCHEMA_OPERACIONAL)
        estructura.llaves_primarias[tabla] = tuple(pk["constrained_columns"])

        for fk in inspector.get_foreign_keys(tabla, schema=SCHEMA_OPERACIONAL):
            estructura.llaves_foraneas.add(
                (
                    tabla,
                    fk["constrained_columns"][0],
                    fk["referred_table"],
                    fk["referred_columns"][0],
                    fk.get("options", {}).get("ondelete"),
                )
            )

        for indice in inspector.get_indexes(tabla, schema=SCHEMA_OPERACIONAL):
            # PostgreSQL materialises every UNIQUE constraint as an index too;
            # duplicates_constraint marks those, leaving the declared ones.
            if indice.get("duplicates_constraint"):
                continue
            estructura.indices_explicitos.add(
                (tabla, indice["name"], tuple(indice["column_names"]))
            )

        for unica in inspector.get_unique_constraints(tabla, schema=SCHEMA_OPERACIONAL):
            estructura.restricciones_unique.add(
                (tabla, unica["name"], tuple(unica["column_names"]))
            )

        for check in inspector.get_check_constraints(tabla, schema=SCHEMA_OPERACIONAL):
            estructura.restricciones_check.add((tabla, check["name"]))

        columnas = inspector.get_columns(tabla, schema=SCHEMA_OPERACIONAL)
        estructura.columnas[tabla] = {c["name"] for c in columnas}
        estructura.columnas_nullable[tabla] = {
            c["name"] for c in columnas if c["nullable"]
        }
        for columna in columnas:
            estructura.tipos[(tabla, columna["name"])] = _describir_tipo(columna["type"])

    return estructura


def _esquemas(engine) -> set[str]:
    return set(inspect(engine).get_schema_names())


def _revision_estampada(engine) -> str | None:
    """Revision recorded in alembic_version, or None if the table is not there yet."""
    with engine.connect() as conexion:
        existe = conexion.execute(
            text("select to_regclass('public.alembic_version')")
        ).scalar()
        if existe is None:
            return None
        return conexion.execute(text("select version_num from alembic_version")).scalar()


@dataclass
class ResultadoDelCiclo:
    revision_inicial: str
    estructura_tras_primer_upgrade: EstructuraDesplegada
    esquemas_tras_primer_upgrade: set[str]
    esquemas_tras_downgrade: set[str]
    estructura_tras_segundo_upgrade: EstructuraDesplegada
    revision_final: str | None
    diferencias_de_alembic_check: str | None


@pytest.fixture(scope="session")
def ciclo() -> ResultadoDelCiclo:
    """Run upgrade -> downgrade -> upgrade -> check once, and snapshot each step."""
    url = os.environ[VARIABLE_DE_ENTORNO]
    engine = create_engine(url)

    with engine.connect() as conexion:
        nombre = conexion.execute(text("select current_database()")).scalar()
    if nombre != NOMBRE_DE_BASE_REQUERIDO:
        # No URL in the message: it carries credentials.
        pytest.fail(
            f"{VARIABLE_DE_ENTORNO} apunta a la base '{nombre}'. Esta validación "
            f"borra y recrea el esquema {SCHEMA_OPERACIONAL} completo, así que sólo "
            f"se ejecuta contra la base dedicada '{NOMBRE_DE_BASE_REQUERIDO}'."
        )

    config = construir_config_alembic()
    revision_inicial = ScriptDirectory.from_config(config).get_bases()[0]

    estampada = _revision_estampada(engine)
    if SCHEMA_OPERACIONAL in _esquemas(engine) and estampada != revision_inicial:
        pytest.fail(
            f"La base '{nombre}' ya tiene un esquema {SCHEMA_OPERACIONAL} que esta "
            f"revisión no creó (alembic_version: {estampada!r}). Se aborta en lugar "
            "de adoptarlo o eliminarlo."
        )

    with pytest.MonkeyPatch.context() as parche:
        # alembic/env.py resolves the URL from settings, not from the Config, so
        # this is what actually keeps the cycle away from the development database.
        parche.setattr(settings, "database_url", url)

        if estampada == revision_inicial:
            command.downgrade(config, "base")

        command.upgrade(config, "head")
        estructura_1 = _tomar_estructura(engine)
        esquemas_1 = _esquemas(engine)

        command.downgrade(config, "base")
        esquemas_tras_downgrade = _esquemas(engine)

        command.upgrade(config, "head")
        estructura_2 = _tomar_estructura(engine)

        try:
            command.check(config)
            diferencias = None
        except AutogenerateDiffsDetected as error:
            diferencias = str(error)

        revision_final = _revision_estampada(engine)

    engine.dispose()
    return ResultadoDelCiclo(
        revision_inicial=revision_inicial,
        estructura_tras_primer_upgrade=estructura_1,
        esquemas_tras_primer_upgrade=esquemas_1,
        esquemas_tras_downgrade=esquemas_tras_downgrade,
        estructura_tras_segundo_upgrade=estructura_2,
        revision_final=revision_final,
        diferencias_de_alembic_check=diferencias,
    )


